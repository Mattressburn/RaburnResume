import { useEffect, useRef, useState } from 'react'
import { createPortal } from 'react-dom'
import { m } from 'framer-motion'
import { site } from '../data/site'
import { ask, splitCites, CITES, LIMITS } from '../lib/ask-client'
import { ease, useReducedMotionPref } from '../lib/motion'

const COPY = {
  header: 'Ask about Matt · answers come from this page and the public case study, generated by Claude. Rate limits only; no questions or addresses are stored.',
  limit: "That's the limit for this visit. Email Matt for the rest.",
  paused: 'Live answers are paused; these are pre-written.',
  error: "Can't answer live right now. Email Matt.",
  truncated: 'Email Matt for the rest',
}
const SECTION_KEYS = { 'case study': 'case-study', 'the system': 'system' }

// "...text. (Experience)" -> { text, cite: 'experience' }; unmapped names leave the text unchanged.
function fallbackAnswer(raw) {
  const mt = raw.match(/^([\s\S]*?)\s*\(([^()]+)\)\s*$/)
  if (!mt) return { text: raw, cites: [] }
  const name = mt[2].trim().toLowerCase()
  const key = SECTION_KEYS[name] || name
  return Object.hasOwn(CITES, key) ? { text: mt[1], cites: [key] } : { text: raw, cites: [] }
}

// Hide a half-arrived "[cite:sys" while streaming.
const stripPartial = (s) => s.replace(/\[cite:[a-z-]*$/, '').replace(/\[c?i?t?e?$/, '')

function Cite({ k, onNav }) {
  const external = k === 'case-study'
  return (
    <a
      href={CITES[k]}
      onClick={external ? undefined : onNav}
      {...(external ? { target: '_blank', rel: 'noopener noreferrer' } : {})}
      className="inline-block rounded-full border border-line2 px-2 py-[1px] mr-2 font-mono text-[11px] text-accent"
    >
      {external ? 'Case study' : `#${k}`}
    </a>
  )
}

const mail = (
  <a href={`mailto:${site.contact.email}`} className="text-accent underline">{site.contact.email}</a>
)

export default function AskPanel({ open, initialQuestion, onClose }) {
  const reduced = useReducedMotionPref()
  const [msgs, setMsgs] = useState([])
  const [asked, setAsked] = useState(0)
  const [paused, setPaused] = useState(false)
  const [limited, setLimited] = useState(false)
  const [busy, setBusy] = useState(false)
  const [draft, setDraft] = useState('')
  const inputRef = useRef(null)
  const rootRef = useRef(null)
  const sent = useRef(false)
  const state = useRef({})
  state.current = { msgs, asked, paused, limited, busy }

  const patchLast = (p) => setMsgs((ms) => ms.map((x, i) => (i === ms.length - 1 ? { ...x, ...p } : x)))

  async function send(raw) {
    const { msgs: cur, asked: n, paused: isPaused, limited: isLimited, busy: isBusy } = state.current
    const q = raw.trim().slice(0, LIMITS.maxChars)
    if (!q || isBusy || isLimited || n >= LIMITS.maxQuestions) return
    setAsked(n + 1)
    const userMsg = { role: 'user', text: q }
    const answerFromFallback = (paused) => {
      const fb = site.ask.fallback[q]
      return fb ? { role: 'assistant', ...fallbackAnswer(fb) } : { role: 'assistant', text: COPY.error, cites: [], email: true, paused }
    }
    if (isPaused) {
      setMsgs([...cur, userMsg, answerFromFallback(true)])
      return
    }
    setMsgs([...cur, userMsg, { role: 'assistant', text: '', cites: [], streaming: true }])
    setBusy(true)
    const history = [...cur, userMsg].map((x) => ({ role: x.role, content: x.text }))
    const r = await ask(history, { onChunk: (t) => patchLast({ text: splitCites(stripPartial(t)).body }) })
    setBusy(false)
    if (r.status === 'ok') {
      const { body, cites } = splitCites(r.text)
      patchLast({ text: body.trim(), cites, streaming: false, email: cites.length === 0 })
    } else if (r.status === 'ip') {
      setLimited(true)
      patchLast({ text: COPY.limit, cites: [], streaming: false, email: true })
    } else if (r.status === 'global' || r.status === 'paused') {
      setPaused(true)
      setMsgs((ms) => [...ms.slice(0, -1), answerFromFallback(true)])
    } else {
      patchLast({ text: COPY.error, cites: [], streaming: false, email: true })
    }
  }

  // Send the question that opened the panel, once per opening.
  useEffect(() => {
    if (!open) { sent.current = false; return }
    if (initialQuestion && !sent.current) {
      sent.current = true
      send(initialQuestion)
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open, initialQuestion])

  // Focus in, page behind inert, Escape closes.
  useEffect(() => {
    if (!open) return undefined
    inputRef.current?.focus()
    const others = [...document.body.children].filter((el) => el !== rootRef.current)
    const prev = others.map((el) => el.hasAttribute('inert'))
    others.forEach((el) => el.setAttribute('inert', ''))
    const onKey = (e) => { if (e.key === 'Escape') onClose() }
    document.addEventListener('keydown', onKey)
    return () => {
      document.removeEventListener('keydown', onKey)
      others.forEach((el, i) => { if (!prev[i]) el.removeAttribute('inert') })
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open])

  if (!open) return null
  const atLimit = limited || asked >= LIMITS.maxQuestions
  const Panel = reduced ? 'div' : m.div
  const motionProps = reduced ? {} : { initial: { x: '100%' }, animate: { x: 0 }, transition: { duration: 0.3, ease } }

  return createPortal(
    <div ref={rootRef}>
      <Panel
        role="dialog"
        aria-modal="true"
        aria-label="Ask about Matt"
        className="fixed right-0 top-0 h-full w-full sm:w-[420px] z-50 flex flex-col bg-bg2 border-l border-line2"
        {...motionProps}
      >
        <div className="flex items-start gap-3 p-4 border-b border-line">
          <p className="flex-1 text-[12px] text-fg3">{COPY.header}</p>
          <button type="button" onClick={onClose} aria-label="Close" className="text-fg2 text-[18px] leading-none px-2">×</button>
        </div>
        {paused && <p className="px-4 pt-3 font-mono text-[11px] text-accent">{COPY.paused}</p>}
        <div className="flex-1 overflow-y-auto p-4 space-y-4" aria-live="polite">
          {msgs.map((x, i) => (
            <div key={i} className={x.role === 'user' ? 'text-fg2' : 'text-fg'}>
              <p className="text-[14px] whitespace-pre-wrap">{x.text}</p>
              {x.role === 'assistant' && !x.streaming && (
                <div className="mt-2 text-[12px]">
                  {(x.cites || []).map((k) => <Cite key={k} k={k} onNav={onClose} />)}
                  {x.email && <span className="text-fg3">{x.text === COPY.limit || x.text === COPY.error ? null : `${COPY.truncated}: `}{mail}</span>}
                </div>
              )}
            </div>
          ))}
          {paused && !atLimit && (
            <div className="flex flex-wrap gap-2">
              {site.ask.suggestions.map((q) => (
                <button key={q} type="button" onClick={() => send(q)} className="rounded-full border border-line2 px-3 py-1 text-[12px] text-fg2 hover:text-fg">{q}</button>
              ))}
            </div>
          )}
          {atLimit && !limited && <p className="text-[14px] text-fg">{COPY.limit}</p>}
        </div>
        <form
          aria-label="Ask a follow-up"
          onSubmit={(e) => { e.preventDefault(); const q = draft; setDraft(''); send(q) }}
          className="p-4 border-t border-line"
        >
          <div className="flex gap-2">
            <input
              ref={inputRef}
              type="text"
              value={draft}
              maxLength={LIMITS.maxChars}
              disabled={atLimit}
              onChange={(e) => setDraft(e.target.value)}
              aria-label="Your question"
              className="flex-1 min-w-0 rounded-md border border-line2 bg-bg px-3 py-[10px] text-[13px] text-fg disabled:opacity-50"
            />
            <button type="submit" disabled={atLimit || busy} className="rounded-md bg-accent text-bg px-4 text-[13px] font-semibold disabled:opacity-50">Ask</button>
          </div>
          <p className="font-mono text-[10px] text-fg3 mt-2">{Math.min(asked, LIMITS.maxQuestions)} of {LIMITS.maxQuestions}</p>
        </form>
      </Panel>
    </div>,
    document.body,
  )
}
